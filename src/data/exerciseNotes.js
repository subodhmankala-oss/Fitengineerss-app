let byKey = null;
const strip = (name) => String(name || '').replace(/\(.*?\)/g, ' ');

function index() {
  if (byKey) return byKey;
  byKey = new Map();
  Object.entries(NOTES).forEach(([name, note]) => {
    byKey.set(exerciseNameKey(name), note);
    const bare = exerciseNameKey(strip(name));
    if (bare && !byKey.has(bare)) byKey.set(bare, note);
  });
  return byKey;
}

// The written note for an exercise name, or '' when there isn't one
// (custom exercises, or names not in the library).
export function getExerciseNote(name) {
  if (!name) return '';
  const map = index();
  return map.get(exerciseNameKey(name)) || map.get(exerciseNameKey(strip(name))) || '';
}

